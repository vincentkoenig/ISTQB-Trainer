-- Stellt die Fragen vom Leitner-System auf FSRS um.
-- Muss vor dem Start der neuen Web-/App-Version angewendet werden.
-- Rein additiv: box, times_seen, times_correct und next_review bleiben erhalten.

begin;

alter table questions
    add column if not exists fsrs_state integer not null default 1,  -- 1 Learning, 2 Review, 3 Relearning
    add column if not exists fsrs_step integer default 0,
    add column if not exists fsrs_stability double precision,
    add column if not exists fsrs_difficulty double precision,
    add column if not exists last_review timestamp;

-- Bisher reichten wenige richtige Antworten innerhalb von Minuten für Box 5.
-- Die Box sagt also wenig über das echte Behalten aus, daher bewusst vorsichtige Startwerte.
-- Box 1 und ungesehene Fragen starten als neue Karten.
update questions
set fsrs_state = 2,
    fsrs_step = null,
    fsrs_difficulty = 5.0,
    fsrs_stability = case box when 2 then 1 when 3 then 3 when 4 then 7 else 14 end,
    last_review = least(next_review, timezone('utc', now()))
where box >= 2
  and times_seen > 0
  and last_review is null;

-- Jede Antwort, als Grundlage für einen späteren FSRS-Optimizer.
create table if not exists review_logs (
    id integer generated by default as identity primary key,
    question_id integer not null references questions (id) on delete cascade,
    rating integer not null check (rating between 1 and 4),
    source varchar(20) not null default 'practice',
    reviewed_at timestamp not null default timezone('utc', now())
);

create index if not exists review_logs_question_id_idx on review_logs (question_id);

alter table review_logs enable row level security;

grant select, insert on review_logs to anon;

drop policy if exists "review_logs_anon_select" on review_logs;
create policy "review_logs_anon_select" on review_logs
    for select to anon using (true);

drop policy if exists "review_logs_anon_insert" on review_logs;
create policy "review_logs_anon_insert" on review_logs
    for insert to anon with check (true);

commit;
